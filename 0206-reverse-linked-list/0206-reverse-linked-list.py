# Definition for singly-linked list.
# class ListNode:
#     def __init__(self, val=0, next=None):
#         self.val = val
#         self.next = next
class Solution:
    def reverseList(self, head: ListNode | None) -> ListNode | None:
        pointer = head
        prev = None
        while pointer != None:
            nextnode = pointer.next
            pointer.next = prev
            prev = pointer
            pointer = nextnode
        return prev
        


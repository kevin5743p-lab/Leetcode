# Definition for singly-linked list.
# class ListNode:
#     def __init__(self, val=0, next=None):
#         self.val = val
#         self.next = next
class Solution:
    def isPalindrome(self, head: ListNode | None) -> bool:
        pointer = head
        arr = list()
        while pointer:
            arr.append(pointer.val)
            pointer = pointer.next
        lst = arr.copy()
        arr.reverse()
        if arr == lst:
            return True
        return False
        

